/* Dot pictures for the dark capability panels (lit dots glow in the accent). 24 x 24 grids. */
const blank = (n = 24) => "0".repeat(n);
function pic(lines: string[]) {
  const out = [...lines.map((l) => l.padEnd(24, "0").slice(0, 24))];
  while (out.length < 24) out.push(blank());
  return out;
}
